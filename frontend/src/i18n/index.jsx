const getByPath = (obj, path) => {
  if (!obj || !path) return undefined;
  const parts = String(path).split('.');
  let cur = obj;
  for (const p of parts) {
    if (cur && typeof cur === 'object' && p in cur) {
      cur = cur[p];
    } else {
      return undefined;
    }
  }
  return cur;
};

const buildResourceIndex = (lang) => {
  const index = {};
  const traverse = (obj, prefix = '') => {
    if (!obj || typeof obj !== 'object') return;
    for (const [k, v] of Object.entries(obj)) {
      const fullKey = prefix ? `${prefix}.${k}` : k;
      if (typeof v === 'string') {
        const cleanVal = v.trim();
        index[fullKey.toLowerCase()] = cleanVal;
        index[k.toLowerCase()] = cleanVal;
        const enVal = getByPath(resources.en, fullKey);
        if (typeof enVal === 'string' && enVal.trim()) {
          index[enVal.trim().toLowerCase()] = cleanVal;
        }
      } else if (typeof v === 'object') {
        traverse(v, fullKey);
      }
    }
  };
  traverse(resources[lang]);
  return index;
};

const RESOURCE_INDEX = {
  en: buildResourceIndex('en'),
  am: buildResourceIndex('am'),
  om: buildResourceIndex('om'),
};

const LanguageContext = createContext({
  t: (k, d) => d || k,
  i18n: { language: 'en', changeLanguage: () => {} },
  currentLang: 'en',
  changeLanguage: () => {},
});

export const LanguageProvider = ({ children }) => {
  const [currentLang, setCurrentLang] = useState(() => {
    migrateLegacyStorage();
    return storage.getLanguage() || 'en';
  });

  const changeLanguage = useCallback((code) => {
    if (resources[code]) {
      setCurrentLang(code);
      storage.setLanguage(code);
      document.documentElement.lang = code;

      try {
        const rawUser = storage.getUser();
        if (rawUser) {
          const userObj = JSON.parse(rawUser);
          userObj.preferredLanguage = code;
          storage.setUser(JSON.stringify(userObj));
        }
      } catch {
      }
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = currentLang;
  }, [currentLang]);

  const t = useCallback((keyPath, defaultText = '') => {
    if (!keyPath) return '';
    const cleanKey = String(keyPath).trim();
    const cleanDefault = defaultText ? String(defaultText).trim() : '';

    if (currentLang === 'en') {
      if (cleanKey.includes('.')) {
        const val = getByPath(resources.en, cleanKey);
        if (typeof val === 'string' && val) return val;
      }
      const idxEn = RESOURCE_INDEX.en || {};
      const lowKey = cleanKey.toLowerCase();
      if (idxEn[lowKey]) return idxEn[lowKey];
      return cleanDefault || cleanKey;
    }

    if (cleanKey.includes('.')) {
      const val = getByPath(resources[currentLang], cleanKey);
      if (typeof val === 'string' && val) return val;
    }

    const idx = RESOURCE_INDEX[currentLang] || {};
    const lowKey = cleanKey.toLowerCase();
    const lowDef = cleanDefault ? cleanDefault.toLowerCase() : '';

    if (idx[lowKey]) return idx[lowKey];

    if (lowDef && idx[lowDef]) return idx[lowDef];

    const dict = PHRASE_DICTIONARY[currentLang] || {};
    if (dict[lowKey]) return dict[lowKey];
    if (lowDef && dict[lowDef]) return dict[lowDef];

    if (cleanKey.includes('.')) {
      const enVal = getByPath(resources.en, cleanKey);
      if (typeof enVal === 'string' && enVal) {
        const lowEn = enVal.toLowerCase();
        if (idx[lowEn]) return idx[lowEn];
        if (dict[lowEn]) return dict[lowEn];
        return cleanDefault || enVal;
      }
    }

    return cleanDefault || cleanKey;
  }, [currentLang]);

  const i18n = {
    language: currentLang,
    changeLanguage,
    languages: ['en', 'am', 'om'],
  };

  return (
    <LanguageContext.Provider value={{ t, i18n, currentLang, changeLanguage }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useTranslation = () => {
  return useContext(LanguageContext);
};

export default LanguageProvider;
